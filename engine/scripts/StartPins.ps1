# Script action: replace the default Start menu pins (ReviOS approach, STARTMENU.cmd + start-menu.yml).
# Pinned set: Microsoft Store, Settings, Notepad, Paint, File Explorer, Calculator.
#   1. policy  HKLM\SOFTWARE\Microsoft\PolicyManager\current\device\Start\ConfigureStartPins  (JSON, REG_SZ)  -> catalog Registry action
#   2. LayoutModification.json / .xml in the Default user's  AppData\Local\Microsoft\Windows\Shell  (new accounts)
#      and in every existing profile's Shell folder
#   3. delete each profile's  Packages\Microsoft.Windows.StartMenuExperienceHost*\LocalState\start*.bin
#   4. delete per-user  CloudStore\Store\Cache\DefaultAccount\*start.tilegrid*  keys  and  Software\Microsoft\Windows\CurrentVersion\Start\Config
#   5. restart StartMenuExperienceHost so it re-reads the layout
# Not implemented: ReviOS also copies a 38 KB DefaultLayouts.xml (Windows' stock education/commercial layouts); its purpose
# is unverified, so it is skipped. Unverified: whether ConfigureStartPins takes effect on Windows 11 Pro 24H2 (see PLAN.md).
# Revert: removes the layout files this tool wrote; start*.bin/tilegrid are regenerated by Windows.

return @{
    Test = {
        param($Action)
        $json = '{"pinnedList":[{"packagedAppId":"Microsoft.WindowsStore_8wekyb3d8bbwe!App"},{"packagedAppId":"windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.immersivecontrolpanel"},{"packagedAppId":"Microsoft.WindowsNotepad_8wekyb3d8bbwe!App"},{"packagedAppId":"Microsoft.Paint_8wekyb3d8bbwe!App"},{"desktopAppLink":"%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\File Explorer.lnk"},{"packagedAppId":"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"}]}'
        $def = Join-Path $env:SystemDrive 'Users\Default\AppData\Local\Microsoft\Windows\Shell\LayoutModification.json'
        if (-not (Test-Path -LiteralPath $def)) { return @{ Status = 'Pending'; Detail = 'Default-user LayoutModification.json missing'; Prior = $null } }
        if ((Get-Content -LiteralPath $def -Raw).Trim() -ne $json) { return @{ Status = 'Pending'; Detail = 'Default-user layout differs'; Prior = $null } }
        # existing profiles
        foreach ($u in @(Get-ChildItem (Join-Path $env:SystemDrive 'Users') -Directory -ErrorAction SilentlyContinue)) {
            if ($u.Name -in @('Default', 'Public', 'All Users', 'Default User')) { continue }
            if (-not (Test-Path -LiteralPath (Join-Path $u.FullName 'NTUSER.DAT'))) { continue }
            $f = Join-Path $u.FullName 'AppData\Local\Microsoft\Windows\Shell\LayoutModification.json'
            if (-not (Test-Path -LiteralPath $f)) { return @{ Status = 'Pending'; Detail = "layout missing for $($u.Name)"; Prior = $null } }
        }
        return @{ Status = 'Applied'; Detail = ''; Prior = $null }
    }

    Apply = {
        param($Action, $Test)
        $json = '{"pinnedList":[{"packagedAppId":"Microsoft.WindowsStore_8wekyb3d8bbwe!App"},{"packagedAppId":"windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.immersivecontrolpanel"},{"packagedAppId":"Microsoft.WindowsNotepad_8wekyb3d8bbwe!App"},{"packagedAppId":"Microsoft.Paint_8wekyb3d8bbwe!App"},{"desktopAppLink":"%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\File Explorer.lnk"},{"packagedAppId":"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"}]}'
        $xml = '<LayoutModificationTemplate xmlns:defaultlayout="http://schemas.microsoft.com/Start/2014/FullDefaultLayout" xmlns:start="http://schemas.microsoft.com/Start/2014/StartLayout" Version="1" xmlns="http://schemas.microsoft.com/Start/2014/LayoutModification">' +
        '<LayoutOptions StartTileGroupCellWidth="6" /><DefaultLayoutOverride><StartLayoutCollection><defaultlayout:StartLayout GroupCellWidth="6" /></StartLayoutCollection></DefaultLayoutOverride></LayoutModificationTemplate>'
        $utf8 = New-Object Text.UTF8Encoding($false)
        $writeLayout = {
            param($localAppData)
            $dir = Join-Path $localAppData 'Microsoft\Windows\Shell'
            [IO.Directory]::CreateDirectory($dir) | Out-Null
            [IO.File]::WriteAllText((Join-Path $dir 'LayoutModification.json'), $json, $utf8)
            [IO.File]::WriteAllText((Join-Path $dir 'LayoutModification.xml'), $xml, $utf8)
        }
        # Default user (new accounts)
        & $writeLayout (Join-Path $env:SystemDrive 'Users\Default\AppData\Local')

        foreach ($u in @(Get-ChildItem (Join-Path $env:SystemDrive 'Users') -Directory -ErrorAction SilentlyContinue)) {
            if ($u.Name -in @('Default', 'Public', 'All Users', 'Default User')) { continue }
            if (-not (Test-Path -LiteralPath (Join-Path $u.FullName 'NTUSER.DAT'))) { continue }
            $la = Join-Path $u.FullName 'AppData\Local'
            & $writeLayout $la
            foreach ($pkg in @(Get-ChildItem (Join-Path $la 'Packages') -Directory -Filter 'Microsoft.Windows.StartMenuExperienceHost*' -ErrorAction SilentlyContinue)) {
                $ls = Join-Path $pkg.FullName 'LocalState'
                foreach ($b in @(Get-ChildItem $ls -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -match '^start\d*\.bin$' })) {
                    Remove-Item -LiteralPath $b.FullName -Force -ErrorAction SilentlyContinue
                }
            }
        }
        # per-user registry cleanup (tilegrid cache + Start\Config) for every user hive
        foreach ($t in @(Get-UserTargets)) {
            if ($t.Kind -ne 'user') { continue }
            $sub = ($t.Root -replace '^HKU\\', '')
            $cache = [Microsoft.Win32.Registry]::Users.OpenSubKey("$sub\SOFTWARE\Microsoft\Windows\CurrentVersion\CloudStore\Store\Cache\DefaultAccount", $true)
            if ($cache) {
                try { foreach ($n in @($cache.GetSubKeyNames() | Where-Object { $_ -like '*start.tilegrid*' })) { $cache.DeleteSubKeyTree($n, $false) } }
                finally { $cache.Close() }
            }
            $start = [Microsoft.Win32.Registry]::Users.OpenSubKey("$sub\Software\Microsoft\Windows\CurrentVersion\Start", $true)
            if ($start) { try { $start.DeleteValue('Config', $false) } finally { $start.Close() } }
        }
        Get-Process -Name StartMenuExperienceHost -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    }

    Undo = {
        param($Action, $Prior)
        $files = @('LayoutModification.json', 'LayoutModification.xml')
        $dirs = @(Join-Path $env:SystemDrive 'Users\Default\AppData\Local\Microsoft\Windows\Shell')
        foreach ($u in @(Get-ChildItem (Join-Path $env:SystemDrive 'Users') -Directory -ErrorAction SilentlyContinue)) {
            $dirs += Join-Path $u.FullName 'AppData\Local\Microsoft\Windows\Shell'
        }
        foreach ($d in $dirs) { foreach ($f in $files) { Remove-Item -LiteralPath (Join-Path $d $f) -Force -ErrorAction SilentlyContinue } }
        Write-Log WARN 'Layout files removed. Also revert the ConfigureStartPins registry value (it is a separate action in the same tweak).'
    }
}
