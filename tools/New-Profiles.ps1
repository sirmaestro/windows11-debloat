<#
.SYNOPSIS
    Regenerates profiles\*.psd1 from the ticked [x] items in TWEAKS.md.
.DESCRIPTION
    all       every ticked tweak
    base      ticked tweaks except those in edge / defender / updates
    edge      Edge removal and Edge re-install protection
    defender  Defender disable + UI hide (needs Tamper Protection off first)
    updates   upd.* (Windows Update pause etc.) - apply LAST, after you finished updating Windows
    Suggested order on a fresh install:  Windows Update fully -> install browser -> base -> edge -> defender -> reboot -> updates
#>
$root = Split-Path $PSScriptRoot -Parent
$ticked = New-Object System.Collections.Generic.List[string]
foreach ($line in [IO.File]::ReadAllLines((Join-Path $root 'TWEAKS.md'), [Text.Encoding]::UTF8)) {
    if ($line -match '^- \[x\] \*\*([A-Za-z0-9._-]+)\*\*') { $ticked.Add($Matches[1]) }
}
$edge = @('edge.remove-edge', 'edge.block-edge-reinstall', 'edge.keep-webview2', 'edge.edgeupdate-manual', 'svc.edgeupdate-manual')
$defender = @('sec.defender-disable', 'sec.defender-ui-hide')
$updates = @($ticked | Where-Object { $_ -like 'upd.*' })

$sets = [ordered]@{
    all      = @($ticked)
    base     = @($ticked | Where-Object { ($edge + $defender + $updates) -notcontains $_ })
    edge     = @($ticked | Where-Object { $edge -contains $_ })
    defender = @($ticked | Where-Object { $defender -contains $_ })
    updates  = $updates
}
$desc = @{
    all      = 'Every tweak ticked in TWEAKS.md.'
    base     = 'Everything ticked except Edge removal, Defender and Windows Update pause.'
    edge     = 'Edge removal and reinstall protection (needs a non-EEA region).'
    defender = 'Disable Defender (turn Tamper Protection off first).'
    updates  = 'Windows Update pause etc. Apply last, after updating Windows.'
}
$dir = Join-Path $root 'profiles'
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
foreach ($k in $sets.Keys) {
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine("# GENERATED by tools\New-Profiles.ps1 from the [x] items in TWEAKS.md. Do not edit by hand.")
    [void]$sb.AppendLine('@{')
    [void]$sb.AppendLine("    Description = '$($desc[$k])'")
    [void]$sb.AppendLine('    Tweaks = @(')
    foreach ($id in $sets[$k]) { [void]$sb.AppendLine("        '$id'") }
    [void]$sb.AppendLine('    )')
    [void]$sb.AppendLine('}')
    [IO.File]::WriteAllText((Join-Path $dir "$k.psd1"), $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
    Write-Host ("{0,-9} {1} tweaks" -f $k, @($sets[$k]).Count)
}
